import { mountLayout } from "./layout.js";
import { loadSolar } from "./data.js";
import { esc } from "./initiatives.js";

mountLayout("solar");
const $ = (s, r = document) => r.querySelector(s);
const fmt = n => Math.round(n).toLocaleString("en-IN");
const fmt1 = n => n.toLocaleString("en-IN", { maximumFractionDigits: 1 });
const has = v => typeof v === "number";
const monthLabel = m => new Date(m + "-01T00:00:00").toLocaleDateString("en-IN", { month: "short", year: "2-digit" });
const fyOf = m => { const [y, mo] = m.split("-").map(Number); const s = mo >= 4 ? y : y - 1; return `${s}-${String(s + 1).slice(2)}`; };
const COLORS = { solar: "#FCC30B", export: "#26BDE2", grid: "#6b7280" };

let data;
init().catch(e => { console.error(e); $("#error").hidden = false; });

async function init() {
  data = await loadSolar();
  $("#sample-banner").hidden = !data.sample;
  if (!data.rows.length) { $("#error").textContent = "No solar readings have been added yet."; $("#error").hidden = false; return; }
  const fys = [...new Set(data.rows.map(r => fyOf(r.month)))].sort().reverse();
  $("#period").innerHTML = `<option value="12">Last 12 months</option>` + fys.map(f => `<option value="${f}">FY ${f}</option>`).join("") + `<option value="all">All time</option>`;
  $("#period").addEventListener("change", render);
  $("#csv").addEventListener("click", downloadCsv);
  $("#solar-body").hidden = false;
  render();
}

function current() {
  const p = $("#period").value;
  if (p === "all") return data.rows;
  if (p === "12") return data.rows.slice(-12);
  return data.rows.filter(r => fyOf(r.month) === p);
}
const solarOf = r => data.plants.reduce((s, p) => s + (has(r[p.id]) ? r[p.id] : 0), 0);
const sum = (rows, f) => rows.reduce((s, r) => s + (f(r) || 0), 0);

// totals over a set of rows. Solar share = solar ÷ (solar + KSEB import)
function totals(rows) {
  const solar = sum(rows, solarOf), exported = sum(rows, r => r.export), grid = sum(rows, r => r.grid);
  return { solar, exported, grid, share: solar + grid ? solar / (solar + grid) * 100 : null };
}

function render() {
  const rows = current();
  const t = totals(rows);
  const co2 = t.solar / 1000 * data.config.emissionFactorTPerMWh;
  const first = monthLabel(rows[0].month), last = monthLabel(rows[rows.length - 1].month);
  $("#period-note").textContent = `${first} to ${last} · ${rows.length} months`;

  renderCompare();
  const kpis = [
    [fmt(t.solar), "kWh generated by solar"],
    [fmt(t.exported), "kWh exported to the grid"],
    [fmt(t.grid), "kWh imported from KSEB"],
    [t.share == null ? "–" : fmt1(t.share) + "%", "solar share: solar ÷ (solar + KSEB import)"],
    [fmt1(co2), "tonnes CO₂ avoided (est.)"]
  ];
  $("#kpis").className = "stats kpis";
  $("#kpis").innerHTML = kpis.map(([v, l]) => `<div><strong>${v}</strong><span>${l}</span></div>`).join("");

  // plant cards
  const solarTot = t.solar;
  $("#plants").innerHTML = data.plants.map(p => {
    const w = rows.filter(r => has(r[p.id]));
    const tot = sum(w, r => r[p.id]);
    const best = w.length ? w.reduce((a, b) => b[p.id] > a[p.id] ? b : a) : null;
    return `<article class="plant" style="--c:${p.color}">
      <h3>${esc(p.name)} ${p.commissioned ? `<small>commissioned ${new Date(p.commissioned).toLocaleDateString("en-IN", { day: "numeric", month: "short", year: "numeric" })}</small>` : ""}</h3>
      <strong class="plant-total">${w.length ? fmt(tot) : "–"} <small>kWh</small></strong>
      <div class="bar"><span style="width:${solarTot ? tot / solarTot * 100 : 0}%"></span></div>
      <ul>
        <li><span>Share of solar output</span><strong>${fmt1(solarTot ? tot / solarTot * 100 : 0)}%</strong></li>
        <li><span>Monthly average</span><strong>${w.length ? fmt(tot / w.length) + " kWh" : "–"}</strong></li>
        <li><span>Best month</span><strong>${best ? monthLabel(best.month) + " · " + fmt(best[p.id]) : "–"}</strong></li>
        ${p.kWp && w.length ? `<li><span>Specific yield</span><strong>${fmt(tot / p.kWp)} kWh/kWp</strong></li><li><span>Avg per month per kWp</span><strong>${fmt1(tot / p.kWp / w.length)} kWh</strong></li>` : ""}
      </ul></article>`;
  }).join("");

  // charts: monthly, or by financial year when the range is long
  const long = rows.length > 24;
  let groups;
  if (long) {
    const m = new Map();
    rows.forEach(r => { const k = fyOf(r.month); (m.get(k) || m.set(k, []).get(k)).push(r); });
    groups = [...m].map(([k, rs]) => ({ label: "FY " + k.slice(2), rows: rs, partial: rs.length < 12 }));
  } else groups = rows.map(r => ({ label: monthLabel(r.month), rows: [r] }));
  $("#chart-note").textContent = long ? "Showing totals per financial year (April–March). Years with fewer than 12 months of data are partial." : "";

  const plantSeries = data.plants.map(p => ({ name: p.name, color: p.color, values: groups.map(g => sum(g.rows, r => r[p.id])) }));
  legend("#legend-a", plantSeries);
  $("#chart-a").innerHTML = chart(groups.map(g => g.label), plantSeries, true);

  const compare = [
    { name: "Solar generated", color: COLORS.solar, values: groups.map(g => sum(g.rows, solarOf)) },
    { name: "Exported to grid", color: COLORS.export, values: groups.map(g => sum(g.rows, r => r.export)) },
    { name: "Imported from KSEB", color: COLORS.grid, values: groups.map(g => sum(g.rows, r => r.grid)) }
  ];
  legend("#legend-b", compare);
  $("#chart-b").innerHTML = chart(groups.map(g => g.label), compare, false);
  $("#share-row").innerHTML = groups.map(g => { const s = totals(g.rows).share; return `<span><small>${g.label}</small><strong>${s == null ? "–" : fmt(s) + "%"}</strong></span>`; }).join("");

  const cell = v => has(v) ? fmt(v) : "–";
  $("#data-table").innerHTML = `<thead><tr><th>Month</th>${data.plants.map(p => `<th>${esc(p.name)} (kWh)</th>`).join("")}<th>Solar total</th><th>Exported</th><th>KSEB import</th><th>Solar share</th></tr></thead><tbody>`
    + rows.slice().reverse().map(r => { const s = totals([r]).share; return `<tr><th scope="row">${monthLabel(r.month)}</th>${data.plants.map(p => `<td>${cell(r[p.id])}</td>`).join("")}<td>${fmt(solarOf(r))}</td><td>${cell(r.export)}</td><td>${cell(r.grid)}</td><td>${s == null ? "–" : fmt1(s) + "%"}</td></tr>`; }).join("")
    + `<tr class="total"><th scope="row">Total</th>${data.plants.map(p => `<td>${fmt(sum(rows, r => r[p.id]))}</td>`).join("")}<td>${fmt(t.solar)}</td><td>${fmt(t.exported)}</td><td>${fmt(t.grid)}</td><td>${t.share == null ? "–" : fmt1(t.share) + "%"}</td></tr></tbody>`;

  $("#method").innerHTML = `<strong>How these numbers are worked out.</strong>
    <ul class="ticks">
      <li><b>Solar generated</b> is the sum of the three plants (15, 100 and 120 kWp). <b>KSEB import</b> is the units drawn from KSEB (zone 1) as recorded in the college electricity data sheet.</li>
      <li><b>Solar share</b> = solar generated ÷ (solar generated + KSEB import). Energy exported to KSEB is included in generation and not deducted. Diesel generator use is not included.</li>
      <li><b>CO₂ avoided</b> = solar generated × ${data.config.emissionFactorTPerMWh} t per MWh, an estimate (see <a href="carbon.html">carbon impact</a>).</li>
      <li>The 120 kWp plant was commissioned on 22 April 2026, so earlier months show only the 15 and 100 kWp plants.</li>
    </ul>`;
}


// Same calendar months one year earlier vs the months since the newest plant was commissioned
function renderCompare() {
  const box = $("#compare");
  const plant = data.plants.filter(p => p.commissioned).sort((a, b) => a.commissioned.localeCompare(b.commissioned)).pop();
  if (!plant) { box.hidden = true; return; }
  const cm = plant.commissioned.slice(0, 7);
  const after = data.rows.filter(r => r.month >= cm);
  const shift = m => (+m.slice(0, 4) - 1) + m.slice(4);
  const wanted = new Set(after.map(r => shift(r.month)));
  const before = data.rows.filter(r => wanted.has(r.month));
  if (!after.length || before.length !== after.length) { box.hidden = true; return; }
  box.hidden = false;

  const span = rs => `${monthLabel(rs[0].month)} to ${monthLabel(rs[rs.length - 1].month)}`;
  const B = totals(before), A = totals(after), n = after.length;
  const date = new Date(plant.commissioned).toLocaleDateString("en-IN", { day: "numeric", month: "long", year: "numeric" });
  $("#compare-lead").textContent = `The ${plant.name} was commissioned on ${date}. Comparing the same months in consecutive years (${span(before)} against ${span(after)}) keeps the seasons the same.`;

  const pct = (a, b) => b ? (a - b) / b * 100 : null;
  const rowsDef = [
    ["Solar generated per month (kWh)", B.solar / n, A.solar / n, "up"],
    ["KSEB import per month (kWh)", B.grid / n, A.grid / n, "down"],
    ["Exported to KSEB per month (kWh)", B.exported / n, A.exported / n, "neutral"]
  ];
  const sign = v => (v > 0 ? "+" : v < 0 ? "−" : "") + fmt1(Math.abs(v));
  const good = (d, dir) => dir === "neutral" ? "" : (dir === "up") === (d > 0) ? "good" : "bad";
  const trs = rowsDef.map(([label, b, a, dir]) => { const d = pct(a, b); return `<tr><th scope="row">${label}</th><td>${fmt(b)}</td><td>${fmt(a)}</td><td class="${good(d, dir)}">${d == null ? "–" : sign(d) + "%"}</td></tr>`; });
  const dShare = A.share - B.share;
  trs.push(`<tr><th scope="row">Solar share</th><td>${fmt1(B.share)}%</td><td>${fmt1(A.share)}%</td><td class="${good(dShare, "up")}">${sign(dShare)} percentage points</td></tr>`);
  $("#compare-table").innerHTML = `<thead><tr><th></th><th>Before<br><small>${span(before)}</small></th><th>After<br><small>${span(after)}</small></th><th>Change</th></tr></thead><tbody>${trs.join("")}</tbody>`;

  const dGen = pct(A.solar, B.solar), dImp = pct(A.grid, B.grid);
  $("#compare-cards").innerHTML = [
    [fmt1(B.share) + "% → " + fmt1(A.share) + "%", "solar share of electricity"],
    [sign(dGen) + "%", "solar generation per month"],
    [sign(dImp) + "%", "KSEB import per month"]
  ].map(([v, l], i) => `<div class="${i === 2 ? (dImp < 0 ? "good" : "bad") : i === 1 ? (dGen > 0 ? "good" : "bad") : (dShare > 0 ? "good" : "bad")}"><strong>${v}</strong><span>${l}</span></div>`).join("");

  const labels = after.map(r => monthLabel(r.month).split(" ")[0]);
  const series = [
    { name: `Before (${span(before)})`, color: COLORS.grid, values: before.map(r => r.grid) },
    { name: `After (${span(after)})`, color: "#4C9F38", values: after.map(r => r.grid) }
  ];
  legend("#legend-c", series);
  $("#chart-c").innerHTML = chart(labels, series, false);
  $("#compare-note").textContent = `The plant was commissioned partway through ${monthLabel(cm)}, so that month includes only part of its output. Weather and campus electricity demand also differ between years, so treat the comparison as indicative.`;
}

function legend(sel, series) {
  $(sel).innerHTML = series.map(s => `<span><i style="background:${s.color}"></i>${esc(s.name)}</span>`).join("");
}

function niceMax(v) {
  const p = Math.pow(10, Math.floor(Math.log10(v)));
  return [1, 2, 2.5, 5, 10].map(m => m * p).find(m => m >= v);
}
const short = n => n >= 1000 ? (n / 1000) + "k" : String(n);

function chart(labels, series, stacked) {
  const W = 800, H = 300, m = { l: 48, r: 8, t: 14, b: 30 }, iw = W - m.l - m.r, ih = H - m.t - m.b;
  const n = labels.length;
  const tops = labels.map((_, i) => stacked ? series.reduce((s, x) => s + x.values[i], 0) : Math.max(...series.map(x => x.values[i])));
  const max = niceMax(Math.max(...tops, 1));
  const y = v => m.t + ih - v / max * ih;
  const band = iw / n, bw = stacked ? band * 0.62 : band * 0.8 / series.length;
  let out = `<svg viewBox="0 0 ${W} ${H}" role="img" aria-label="Bar chart of kWh" class="chart">`;
  for (let t = 0; t <= 4; t++) {
    const v = max / 4 * t;
    out += `<line x1="${m.l}" x2="${W - m.r}" y1="${y(v)}" y2="${y(v)}" class="grid-line"/><text x="${m.l - 6}" y="${y(v) + 4}" text-anchor="end" class="tick">${short(v)}</text>`;
  }
  labels.forEach((lab, i) => {
    const x0 = m.l + i * band;
    if (stacked) {
      let acc = 0;
      series.forEach(s => {
        const v = s.values[i], h = v / max * ih;
        if (v) out += `<rect x="${x0 + (band - bw) / 2}" y="${y(acc + v)}" width="${bw}" height="${h}" fill="${s.color}"><title>${lab} · ${esc(s.name)}: ${fmt(v)} kWh</title></rect>`;
        acc += v;
      });
    } else {
      series.forEach((s, k) => {
        const v = s.values[i];
        out += `<rect x="${x0 + band * 0.1 + k * bw}" y="${y(v)}" width="${Math.max(bw - 1, 1)}" height="${v / max * ih}" fill="${s.color}"><title>${lab} · ${esc(s.name)}: ${fmt(v)} kWh</title></rect>`;
      });
    }
    if (n <= 14 || i % Math.ceil(n / 14) === 0) out += `<text x="${x0 + band / 2}" y="${H - 10}" text-anchor="middle" class="tick">${lab}</text>`;
  });
  return out + `<text x="${m.l}" y="9" class="tick">kWh</text></svg>`;
}

function downloadCsv() {
  const rows = current();
  const head = ["month", ...data.plants.map(p => p.name), "solar_total_kwh", "export_kwh", "kseb_import_kwh"];
  const lines = [head.join(",")].concat(rows.map(r => [r.month, ...data.plants.map(p => has(r[p.id]) ? r[p.id] : ""), solarOf(r), has(r.export) ? r.export : "", r.grid].join(",")));
  const a = document.createElement("a");
  a.href = URL.createObjectURL(new Blob([lines.join("\n")], { type: "text/csv" }));
  a.download = "solar-data.csv";
  a.click();
  URL.revokeObjectURL(a.href);
}
